def glossary_html() -> str:
    rows = []
    for k, v in TERMS:
        rows.append(f"<div class='sec'>{k}</div>" if v is None else f"<dt>{k}</dt><dd>{v}</dd>")
    return (f"<style>{CSS}</style><details class='gl'><summary>📖 นิยามศัพท์และวิธีอ่านรายงาน (กดเพื่อเปิด)</summary>"
            f"<dl class='gl'>{''.join(rows)}</dl>"
            "<p class='mute'>ข้อมูลอัปเดตวันละครั้งหลังตลาดสหรัฐฯ ปิด (05:30 น. ไทย) ไม่ใช่ราคาเรียลไทม์ · "
            "ทุกอย่างเป็นข้อสังเกตจากข้อมูล ไม่ใช่คำแนะนำซื้อขาย</p></details>")


def howto(title: str, items: list[str]) -> str:
    return f"<div class='howto'><b>อ่านยังไง:</b> {title}<ul>" + "".join(f"<li>{x}</li>" for x in items) + "</ul></div>"
